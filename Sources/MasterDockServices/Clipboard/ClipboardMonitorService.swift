import Foundation
import AppKit

/// Clipboard history. Nothing is recorded until the user turns history on (privacy consent),
/// password-manager and other private copies are skipped, pinned items are kept forever, and
/// any item can be removed on its own.
public final class ClipboardMonitorService: ObservableObject, @unchecked Sendable {
    public static let shared = ClipboardMonitorService()

    @Published public private(set) var items: [ClipboardItem] = []
    /// True once the user has accepted how clipboard history works (or declined it).
    @Published public private(set) var hasAnsweredPrivacyPrompt: Bool
    /// Whether new copies are recorded. Off until the user turns history on.
    @Published public private(set) var isHistoryEnabled: Bool
    /// Skip copies that apps mark as private (password managers, one-time codes). On by default.
    @Published public var skipsSensitiveContent: Bool {
        didSet { UserDefaults.standard.set(skipsSensitiveContent, forKey: Self.skipSensitiveKey) }
    }

    private var timer: Timer?
    private var lastChangeCount: Int = 0
    /// Limit for unpinned items; pinned items never count against it.
    private let maxHistoryLimit: Int = 50
    private let persistence = PersistenceController.shared

    private static let consentKey = "clipboard_privacy_answered"
    private static let enabledKey = "clipboard_history_enabled"
    private static let skipSensitiveKey = "clipboard_skip_sensitive"

    /// Pasteboard markers apps use for content that should not be saved (nspasteboard.org).
    static let privatePasteboardTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
        NSPasteboard.PasteboardType("Pasteboard generator type")
    ]

    public init() {
        let defaults = UserDefaults.standard
        hasAnsweredPrivacyPrompt = defaults.bool(forKey: Self.consentKey)
        isHistoryEnabled = defaults.bool(forKey: Self.enabledKey)
        skipsSensitiveContent = defaults.object(forKey: Self.skipSensitiveKey) as? Bool ?? true
        loadPersistedHistory()
        startMonitoring()
    }

    // MARK: - Consent

    /// User accepted: start recording copies on this Mac.
    public func enableHistory() {
        setConsent(enabled: true)
    }

    /// User declined: don't record anything (they can turn it on later).
    public func declineHistory() {
        setConsent(enabled: false)
    }

    public func setHistoryEnabled(_ enabled: Bool) {
        setConsent(enabled: enabled)
    }

    private func setConsent(enabled: Bool) {
        let defaults = UserDefaults.standard
        defaults.set(true, forKey: Self.consentKey)
        defaults.set(enabled, forKey: Self.enabledKey)
        hasAnsweredPrivacyPrompt = true
        isHistoryEnabled = enabled
        // Don't import whatever was already on the clipboard before history was turned on.
        lastChangeCount = NSPasteboard.general.changeCount
    }

    // MARK: - Monitoring

    public func startMonitoring() {
        lastChangeCount = NSPasteboard.general.changeCount
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in
            self?.checkForNewClipboardContent()
        }
        // Lets macOS bundle this tiny check with other work so the CPU can stay asleep longer.
        timer?.tolerance = 0.4
    }

    public func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    /// Whether this copy is marked private by the app it came from.
    public static func isPrivateCopy(types: [NSPasteboard.PasteboardType]) -> Bool {
        return types.contains { privatePasteboardTypes.contains($0) }
    }

    private func checkForNewClipboardContent() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard isHistoryEnabled else { return }

        let types = pasteboard.types ?? []
        if skipsSensitiveContent && Self.isPrivateCopy(types: types) { return }

        // 1. Image content
        if types.contains(.png) || types.contains(.tiff) {
            if let imgData = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
                let img = NSImage(data: imgData)
                let sizeStr = img.map { "\(Int($0.size.width)) × \(Int($0.size.height))" } ?? "Image"
                let byteCountStr = ByteCountFormatter.string(fromByteCount: Int64(imgData.count), countStyle: .file)
                appendItem(ClipboardItem(
                    type: .image,
                    imageData: imgData,
                    previewTitle: "Image (\(sizeStr))",
                    previewSubtitle: "\(byteCountStr) • \(timeFormatted(Date()))"
                ))
                return
            }
        }

        // 2. Text content
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let type = ClipboardContentType.classify(string: string)
            let previewTitle = string.prefix(60).replacingOccurrences(of: "\n", with: " ")
            appendItem(ClipboardItem(
                type: type,
                textContent: string,
                previewTitle: String(previewTitle),
                previewSubtitle: "\(string.count) chars • \(timeFormatted(Date()))"
            ))
        }
    }

    private func appendItem(_ item: ClipboardItem) {
        DispatchQueue.main.async {
            // Copying something already in the list moves it up instead of adding a duplicate.
            if let existing = self.items.firstIndex(where: { $0.textContent == item.textContent && $0.imageData == item.imageData }) {
                if self.items[existing].isPinned { return }
                self.items.remove(at: existing)
            }
            self.items.append(item)
            self.normalize()
            self.persistHistory()
        }
    }

    /// Pinned first (in pin order), then newest unpinned, trimmed to the history limit.
    private func normalize() {
        let pinned = items.filter { $0.isPinned }
        let recent = items.filter { !$0.isPinned }
            .sorted { $0.timestamp > $1.timestamp }
            .prefix(maxHistoryLimit)
        items = pinned + recent
    }

    // MARK: - Item actions

    public func togglePin(_ id: UUID) {
        DispatchQueue.main.async {
            guard let index = self.items.firstIndex(where: { $0.id == id }) else { return }
            var item = self.items.remove(at: index)
            item.isPinned.toggle()
            if item.isPinned {
                // Newly pinned items go to the end of the pinned group.
                let lastPinned = self.items.lastIndex(where: { $0.isPinned }) ?? -1
                self.items.insert(item, at: lastPinned + 1)
            } else {
                self.items.append(item)
            }
            self.normalize()
            self.persistHistory()
        }
    }

    public func removeItem(_ id: UUID) {
        DispatchQueue.main.async {
            self.items.removeAll { $0.id == id }
            self.persistHistory()
        }
    }

    public func copyItemToPasteboard(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        if let text = item.textContent {
            pasteboard.setString(text, forType: .string)
            if item.type == .url, let url = URL(string: text) {
                pasteboard.setData(url.dataRepresentation, forType: .URL)
            }
        } else if let data = item.imageData {
            pasteboard.setData(data, forType: .png)
            pasteboard.setData(data, forType: .tiff)
        }
        lastChangeCount = pasteboard.changeCount
    }

    public func pasteItemDirectly(_ item: ClipboardItem) {
        copyItemToPasteboard(item)

        // Synthesize Command + V keystroke to paste into previously active app
        DispatchQueue.global(qos: .userInitiated).asyncAfter(deadline: .now() + 0.15) {
            let src = CGEventSource(stateID: .hidSystemState)
            let vKeyCode: CGKeyCode = 9 // 'v' key

            if let keyDown = CGEvent(keyboardEventSource: src, virtualKey: vKeyCode, keyDown: true),
               let keyUp = CGEvent(keyboardEventSource: src, virtualKey: vKeyCode, keyDown: false) {
                keyDown.flags = .maskCommand
                keyUp.flags = .maskCommand
                keyDown.post(tap: .cghidEventTap)
                keyUp.post(tap: .cghidEventTap)
            }
        }
    }

    /// Clears everything except pinned items.
    public func clearHistory() {
        DispatchQueue.main.async {
            self.items.removeAll { !$0.isPinned }
            self.persistHistory()
        }
    }

    /// Removes pinned items too.
    public func clearEverything() {
        DispatchQueue.main.async {
            self.items.removeAll()
            self.persistHistory()
        }
    }

    private func persistHistory() {
        persistence.save(items, forKey: "clipboard_history")
    }

    private func loadPersistedHistory() {
        if let loaded = persistence.load([ClipboardItem].self, forKey: "clipboard_history") {
            self.items = loaded
            normalize()
        }
    }

    private func timeFormatted(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.dateFormat = "h:mm a"
        return formatter.string(from: date)
    }
}
